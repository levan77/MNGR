export type TranslationKey = keyof typeof translations.en;

// ─── Override storage key ──────────────────────────────────────────────────────
const OVERRIDE_KEY = 'mngr_translation_overrides';
const LANG_KEY     = 'mngr_lang';

// ─── Load / save overrides from localStorage ─────────────────────────────────
export function loadOverrides(): Partial<Record<TranslationKey, string>> {
  if (typeof window === 'undefined') return {};
  try {
    return JSON.parse(localStorage.getItem(OVERRIDE_KEY) ?? '{}');
  } catch {
    return {};
  }
}

export function saveOverrides(overrides: Partial<Record<TranslationKey, string>>) {
  if (typeof window === 'undefined') return;
  localStorage.setItem(OVERRIDE_KEY, JSON.stringify(overrides));
}

export function loadLang(): Lang {
  if (typeof window === 'undefined') return 'ka';
  return (localStorage.getItem(LANG_KEY) as Lang | null) ?? 'ka';
}

export function saveLang(lang: Lang) {
  if (typeof window === 'undefined') return;
  localStorage.setItem(LANG_KEY, lang);
}

// ─── Translate function ───────────────────────────────────────────────────────
export function translate(
  lang: Lang,
  key: TranslationKey,
  overrides: Partial<Record<TranslationKey, string>> = {},
): string {
  if (overrides[key] !== undefined) return overrides[key]!;
  return (translations[lang] as Record<string, string>)[key]
    ?? (translations.en as Record<string, string>)[key]
    ?? key;
}
